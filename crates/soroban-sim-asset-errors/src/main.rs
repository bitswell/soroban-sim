//! Writes the error table of the host's built-in contracts (the Stellar asset
//! contract among them) for `packages/soroban-sim-vitest`, from the host's own
//! `ContractError`: the enum is private to the host crate, so its source file
//! is compiled here as a module and the names and codes are the compiler's.
//!
//!   cargo run -p soroban-sim-asset-errors             write the table
//!   cargo run -p soroban-sim-asset-errors -- --check  fail if the committed table differs

#[path = "../../soroban-sim-host/src/builtin_contracts/contract_error.rs"]
mod contract_error;

use contract_error::ContractError;
use num_traits::FromPrimitive;
use soroban_env_common::{xdr::ScErrorType, Error};
use std::{fs, process::ExitCode};

const TABLE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../packages/soroban-sim-vitest/src/generated/stellar-asset-errors.ts"
);

/// Codes are looked for below this; the host's are all under 16.
const CODES: u32 = 1 << 16;

fn table() -> String {
    let mut rows = String::new();
    for variant in (0..CODES).filter_map(ContractError::from_u32) {
        let name = format!("{variant:?}");
        // `_Reserved1` and the like hold a number the host no longer returns.
        if name.starts_with('_') {
            continue;
        }
        let error = Error::from(variant);
        assert!(error.is_type(ScErrorType::Contract), "{name} is not a contract error");
        rows.push_str(&format!("  ['{name}', {}],\n", error.get_code()));
    }
    format!(
        "// Generated by `cargo run -p soroban-sim-asset-errors` from the host's ContractError\n\
         // (crates/soroban-sim-host/src/builtin_contracts/contract_error.rs). Do not edit:\n\
         // CI fails when this file differs from what that command writes.\n\
         \n\
         /** The host's errors for its built-in contracts, by the code it returns. */\n\
         export const STELLAR_ASSET_ERRORS: readonly [string, number][] = [\n{rows}]\n"
    )
}

fn main() -> ExitCode {
    let table = table();
    match std::env::args().nth(1).as_deref() {
        None => {
            fs::write(TABLE, table).expect("writing the table");
            ExitCode::SUCCESS
        }
        Some("--check") => {
            if fs::read_to_string(TABLE).ok().as_deref() == Some(table.as_str()) {
                return ExitCode::SUCCESS;
            }
            eprintln!("{TABLE} is out of date: run `cargo run -p soroban-sim-asset-errors` and commit the result");
            ExitCode::FAILURE
        }
        Some(other) => {
            eprintln!("unknown argument {other}; the only one is --check");
            ExitCode::from(2)
        }
    }
}
